import { NextRequest, NextResponse } from 'next/server';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { imageBase64, mimeType = 'image/jpeg', apiKey: clientApiKey } = body;

    if (!imageBase64) {
      return NextResponse.json(
        { success: false, error: 'Missing imageBase64 data in request body' },
        { status: 400 }
      );
    }

    const apiKey = clientApiKey || process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        {
          success: false,
          error: 'MISSING_API_KEY',
          message: 'No Gemini API key found. Please configure your GEMINI_API_KEY.',
        },
        { status: 401 }
      );
    }

    // Clean base64 data if it contains a data URL prefix
    const cleanBase64 = imageBase64.replace(/^data:image\/[a-z]+;base64,/, '');

    const prompt = `You are an expert product detection model for sales and hardware catalogs.
Detect every distinct product, item, lock, handle, hinge, bolt, tool, or packaged merchandise in this image.
For EVERY distinct product detected, provide:
1. "name": A concise, descriptive product title or label (e.g. "Mortice Lock 200mm", "SS Butt Hinge", "Tower Bolt").
2. "box_2d": The exact 2D bounding box coordinates formatted as an array [ymin, xmin, ymax, xmax] normalized on a 0 to 1000 integer scale, where ymin is top edge, xmin is left edge, ymax is bottom edge, and xmax is right edge.
3. "estimated_price": Any visible price tag or empty string if not visible.

Return ONLY a valid JSON object matching this schema:
{
  "products": [
    {
      "name": "string",
      "box_2d": [ymin, xmin, ymax, xmax],
      "estimated_price": "string"
    }
  ]
}`;

    const requestPayload = {
      contents: [
        {
          parts: [
            { text: prompt },
            {
              inlineData: {
                mimeType,
                data: cleanBase64,
              },
            },
          ],
        },
      ],
      generationConfig: {
        responseMimeType: 'application/json',
        temperature: 0.1,
      },
    };

    // Try gemini-1.5-flash endpoint
    let endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;
    let res = await fetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(requestPayload),
    });

    // Fallback to gemini-2.5-flash or gemini-1.5-pro if 1.5-flash is temporarily unavailable
    if (!res.ok && res.status === 404) {
      endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`;
      res = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(requestPayload),
      });
    }

    if (!res.ok) {
      const errorText = await res.text();
      console.error('Gemini API Error:', res.status, errorText);
      return NextResponse.json(
        {
          success: false,
          error: 'GEMINI_API_ERROR',
          status: res.status,
          message: errorText,
        },
        { status: res.status }
      );
    }

    const data = await res.json();
    const candidate = data.candidates?.[0];
    const textOutput = candidate?.content?.parts?.[0]?.text;

    if (!textOutput) {
      return NextResponse.json(
        { success: false, error: 'NO_RESPONSE', message: 'No content generated by Gemini.' },
        { status: 500 }
      );
    }

    // Strip optional markdown wrapper
    const cleanJson = textOutput
      .replace(/^```json\s*/i, '')
      .replace(/\s*```$/i, '')
      .trim();

    const parsed = JSON.parse(cleanJson);
    const rawProducts = parsed.products || parsed.items || [];

    // Standardize boxes to percentage coordinates
    const formattedProducts = rawProducts
      .map((item: any, idx: number) => {
        const box = item.box_2d || item.box || item.bounding_box || item.bbox;
        if (!box) return null;

        let ymin = 0,
          xmin = 0,
          ymax = 0,
          xmax = 0;

        if (Array.isArray(box) && box.length === 4) {
          [ymin, xmin, ymax, xmax] = box;
        } else if (typeof box === 'object') {
          ymin = box.ymin ?? box.top ?? 0;
          xmin = box.xmin ?? box.left ?? 0;
          ymax = box.ymax ?? box.bottom ?? 0;
          xmax = box.xmax ?? box.right ?? 0;
        }

        // Determine if coordinates are on 0-1000 scale or 0-1 scale
        const maxVal = Math.max(ymin, xmin, ymax, xmax);
        const scale = maxVal > 1.5 ? 1000 : 1;

        const top = Number(Math.max(0, Math.min(100, (ymin / scale) * 100)).toFixed(2));
        const left = Number(Math.max(0, Math.min(100, (xmin / scale) * 100)).toFixed(2));
        const height = Number(Math.max(2, Math.min(100 - top, ((ymax - ymin) / scale) * 100)).toFixed(2));
        const width = Number(Math.max(2, Math.min(100 - left, ((xmax - xmin) / scale) * 100)).toFixed(2));

        return {
          id: `gemini-${Date.now()}-${idx}`,
          name: item.name || `Product #${idx + 1}`,
          price: item.estimated_price || '',
          top,
          left,
          width,
          height,
          rawBox: [ymin, xmin, ymax, xmax],
        };
      })
      .filter(Boolean);

    return NextResponse.json({
      success: true,
      count: formattedProducts.length,
      products: formattedProducts,
    });
  } catch (error: any) {
    console.error('Unhandled Gemini detection route error:', error);
    return NextResponse.json(
      { success: false, error: error.message || 'Internal server error' },
      { status: 500 }
    );
  }
}
