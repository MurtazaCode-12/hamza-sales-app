import { NextRequest, NextResponse } from 'next/server';
import { getDefaultGeminiKey } from '@/lib/geminiKey';
import { repairAndParseJsonObject } from '@/lib/jsonRepair';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { imageBase64, mimeType = 'image/jpeg', apiKey: clientApiKey } = body;

    if (!imageBase64) {
      return NextResponse.json(
        { success: false, error: 'Missing imageBase64 data in request body' },
        { status: 400 }
      );
    }

    const apiKey = clientApiKey || getDefaultGeminiKey();
    if (!apiKey) {
      return NextResponse.json(
        {
          success: false,
          error: 'MISSING_API_KEY',
          message: 'No Gemini API key found. Please configure your GEMINI_API_KEY.',
        },
        { status: 401 }
      );
    }

    // Clean base64 data if it contains a data URL prefix
    const cleanBase64 = imageBase64.replace(/^data:image\/[a-z]+;base64,/, '');

    const prompt = `You are an expert product detection model for sales and hardware catalogs.
Detect every distinct product, item, lock, handle, hinge, bolt, tool, bracket, or packaged merchandise in this image.
For EVERY distinct product detected, provide:
1. "name": A concise, descriptive product title or label (e.g. "Bearing Kada", "Mortice Lock 200mm", "SS Butt Hinge", "Tower Bolt", "S Hook", "Jhula Rod").
2. "box_2d": The exact 2D bounding box coordinates formatted as an array [ymin, xmin, ymax, xmax] normalized on a 0 to 1000 integer scale, where ymin is top edge, xmin is left edge, ymax is bottom edge, and xmax is right edge.
3. "estimated_price": Any visible price tag, rate, or empty string if not visible.
4. "types": Array of strings of all materials, finishes, or product types listed for this product in text or tables (e.g. ["Bush", "Moulding", "S.S."], ["Brass", "Antique", "Black"], ["Special", "S.S."]). If none or unknown, return [].
5. "sizes": Array of strings of all dimensions, weights, lengths, or sizes listed for this product (e.g. ["1 kg", "1.200 kg", "1.400 kg"], ["12\"", "15\""], ["Small", "Big"], ["25mm", "32mm"]). If none or unknown, return [].

Return ONLY a valid JSON object matching this schema:
{
  "products": [
    {
      "name": "string",
      "box_2d": [ymin, xmin, ymax, xmax],
      "estimated_price": "string",
      "types": ["string"],
      "sizes": ["string"]
    }
  ]
}`;

    const requestPayload = {
      contents: [
        {
          parts: [
            { text: prompt },
            {
              inlineData: {
                mimeType,
                data: cleanBase64,
              },
            },
          ],
        },
      ],
      generationConfig: {
        responseMimeType: 'application/json',
        temperature: 0.1,
        maxOutputTokens: 8192,
      },
    };

    // Multi-model pipeline prioritizing high-quota, ultra-fast models
    const modelCandidates = [
      'gemini-3.5-flash-lite',
      'gemini-flash-lite-latest',
      'gemini-3.1-flash-lite',
      'gemini-3.5-flash',
      'gemini-flash-latest',
    ];

    let data: any = null;
    let lastError: any = null;
    let lastStatus = 500;

    for (const model of modelCandidates) {
      try {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 12000); // 12s timeout per candidate

        const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
        const res = await fetch(endpoint, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(requestPayload),
          signal: controller.signal,
        });
        clearTimeout(timeoutId);

        if (res.ok) {
          data = await res.json();
          break; // Success!
        } else {
          lastStatus = res.status;
          lastError = await res.text();
          console.warn(`Gemini detect model ${model} failed with ${res.status}:`, lastError?.slice(0, 100));
          if (res.status === 429) break;
        }
      } catch (err: any) {
        lastError = err?.message || 'Network error';
        console.warn(`Gemini detect model ${model} exception:`, lastError);
      }
    }

    if (!data) {
      return NextResponse.json(
        {
          success: false,
          error: 'GEMINI_API_ERROR',
          status: lastStatus,
          message: lastError || 'All Gemini detection models failed.',
        },
        { status: lastStatus }
      );
    }
    const candidate = data.candidates?.[0];
    const textOutput = candidate?.content?.parts?.[0]?.text;

    if (!textOutput) {
      return NextResponse.json(
        { success: false, error: 'NO_RESPONSE', message: 'No content generated by Gemini.' },
        { status: 500 }
      );
    }

    const parsed = repairAndParseJsonObject(textOutput) || {};
    const rawProducts = parsed.products || parsed.items || (Array.isArray(parsed) ? parsed : []);

    // Standardize boxes to percentage coordinates
    const formattedProducts = rawProducts
      .map((item: any, idx: number) => {
        const box = item.box_2d || item.box || item.bounding_box || item.bbox;
        if (!box) return null;

        let ymin = 0,
          xmin = 0,
          ymax = 0,
          xmax = 0;

        if (Array.isArray(box) && box.length === 4) {
          [ymin, xmin, ymax, xmax] = box;
        } else if (typeof box === 'object') {
          ymin = box.ymin ?? box.top ?? 0;
          xmin = box.xmin ?? box.left ?? 0;
          ymax = box.ymax ?? box.bottom ?? 0;
          xmax = box.xmax ?? box.right ?? 0;
        }

        // Determine if coordinates are on 0-1000 scale or 0-1 scale
        const maxVal = Math.max(ymin, xmin, ymax, xmax);
        const scale = maxVal > 1.5 ? 1000 : 1;

        const top = Number(Math.max(0, Math.min(100, (ymin / scale) * 100)).toFixed(2));
        const left = Number(Math.max(0, Math.min(100, (xmin / scale) * 100)).toFixed(2));
        const height = Number(Math.max(2, Math.min(100 - top, ((ymax - ymin) / scale) * 100)).toFixed(2));
        const width = Number(Math.max(2, Math.min(100 - left, ((xmax - xmin) / scale) * 100)).toFixed(2));

        const types = Array.isArray(item.types)
          ? item.types.map((t: any) => String(t).trim()).filter(Boolean)
          : [];
        const sizes = Array.isArray(item.sizes)
          ? item.sizes.map((s: any) => String(s).trim()).filter(Boolean)
          : [];

        return {
          id: `gemini-${Date.now()}-${idx}`,
          name: item.name || `Product #${idx + 1}`,
          price: item.estimated_price || '',
          types,
          sizes,
          top,
          left,
          width,
          height,
          rawBox: [ymin, xmin, ymax, xmax],
        };
      })
      .filter(Boolean);

    return NextResponse.json({
      success: true,
      count: formattedProducts.length,
      products: formattedProducts,
    });
  } catch (error: any) {
    console.error('Unhandled Gemini detection route error:', error);
    return NextResponse.json(
      { success: false, error: error.message || 'Internal server error' },
      { status: 500 }
    );
  }
}
